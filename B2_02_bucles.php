<?php
/*
Ejercicio 2: Contar del 1 al 5 (Bucle for)
Concepto: Repetir una instrucción varias veces con un bucle.
Instrucción: Muestra los números del 1 al 5, cada uno en una línea distinta
(usa <br> para saltar de línea en HTML).
*/

    for($i = 1; $i <= 5; $i++) {
        echo $i . "<br>";
    }
?>